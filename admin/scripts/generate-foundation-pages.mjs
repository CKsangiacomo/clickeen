export async function generateFoundationPages() {
  await fs.mkdir(foundationsRoot, { recursive: true });
  const coreStyleCount = await generateCoreStylesPage();
  const colorCount = await generateColorsPage();
  const iconCount = await generateIconsPage();
  await generateTypographyPage();
  const layoutTokenCount = await generateLayoutsPage();
  return { colorCount, coreStyleCount, iconCount, layoutTokenCount };
}

if (process.argv[1] === scriptPath) {
  generateFoundationPages()
    .then(({ colorCount, coreStyleCount, iconCount, layoutTokenCount }) => {
      console.log(`[generate-foundation-pages] Wrote core styles (${coreStyleCount}), colors (${colorCount}), icons (${iconCount}), and layouts (${layoutTokenCount}) pages.`);
    })
    .catch((error) => {
      console.error('[generate-foundation-pages] Failed.', error instanceof Error ? error.message : String(error));
      process.exit(1);
    });
}
