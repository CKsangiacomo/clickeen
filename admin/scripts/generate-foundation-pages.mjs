#!/usr/bin/env node
/* eslint-disable no-console */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  parseEditableDieterTokens,
  TOKEN_FILES,
} from '../functions/_shared/dieter-token-contracts.js';

const scriptPath = fileURLToPath(import.meta.url);
const adminRoot = path.resolve(path.dirname(scriptPath), '..');
const repoRoot = path.resolve(adminRoot, '..');
const foundationsRoot = path.join(adminRoot, 'src', 'html', 'foundations');
const colorTokenPath = path.join(repoRoot, 'dieter', 'tokens', 'dieter-color-tokens.css');
const foundationTokenPath = path.join(repoRoot, TOKEN_FILES.foundation.path);
const iconsManifestPath = path.join(repoRoot, 'dieter', 'icons', 'icons.json');
const iconsSvgRoot = path.join(repoRoot, 'dieter', 'icons', 'svg');

const GENERATED_HEADER = '<!-- Generated by admin/scripts/generate-foundation-pages.mjs. Do not edit directly. -->';

const jsString = (value) => JSON.stringify(value);

const escapeHtml = (value) =>
  String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');

async function writeFileIfChanged(filePath, contents) {
  try {
    const current = await fs.readFile(filePath, 'utf8');
    if (current === contents) return;
  } catch {
    // Missing generated files are expected on a fresh checkout.
  }
  await fs.writeFile(filePath, contents, 'utf8');
}

function stripCssComments(input) {
  return input.replace(/\/\*[\s\S]*?\*\//g, '');
}

function parseCustomProperties(css) {
  const declarations = [];
  const declarationRegex = /(--[a-zA-Z0-9_-]+)\s*:\s*([^;]+);/g;
  let match;
  while ((match = declarationRegex.exec(stripCssComments(css)))) {
    declarations.push({ name: match[1], value: match[2].trim() });
  }
  return declarations;
}

function isColorToken(declaration) {
  if (declaration.name.startsWith('--state-') && !declaration.name.endsWith('-target')) return false;
  return /^(--color-|--role-|--focus-|--state-)/.test(declaration.name);
}

function tokenGroup(name) {
  if (name.startsWith('--color-system-gray') || name === '--color-system-white' || name === '--color-system-black' || name === '--color-system-black-secondary') {
    return 'Neutral';
  }
  if (name.startsWith('--color-system-')) return 'System';
  if (name.startsWith('--color-text')) return 'Text';
  if (name.startsWith('--role-')) return 'Roles';
  if (name.startsWith('--focus-')) return 'Focus';
  if (name.startsWith('--state-')) return 'State';
  return 'Other';
}

function displayName(token) {
  return token.replace(/^--/, '').replace(/-/g, ' ').replace(/\b\w/g, (char) => char.toUpperCase());
}

function coreStyleGroup(name) {
  if (name.startsWith('--space-') || name.startsWith('--vertspace-')) return 'Spacing';
  if (name.startsWith('--control-size-') || name === '--control-padding-inline' || name.startsWith('--control-inline-gap-')) {
    return 'Control sizes';
  }
  if (name.startsWith('--control-radius-')) return 'Radii';
  if (name.startsWith('--shadow-')) return 'Shadows';
  if (name.startsWith('--duration-') || name === '--easing-standard') return 'Motion';
  return null;
}

function coreStylePreviewKind(name) {
  if (name.startsWith('--space-') || name.startsWith('--vertspace-')) return 'spacing';
  if (name.startsWith('--control-size-')) return 'control-size';
  if (name === '--control-padding-inline') return 'control-padding';
  if (name.startsWith('--control-inline-gap-')) return 'control-gap';
  if (name.startsWith('--control-radius-')) return 'radius';
  if (name.startsWith('--shadow-')) return 'shadow';
  return 'motion';
}

function renderCoreStyleSample(entry) {
  const previewKind = coreStylePreviewKind(entry.name);
  const sampleStyle =
    previewKind === 'control-padding'
      ? `padding-inline:var(${entry.name})`
      : previewKind === 'control-gap'
        ? `gap:var(${entry.name})`
        : '';
  const partStyle =
    previewKind === 'spacing'
      ? `inline-size:var(${entry.name})`
      : previewKind === 'control-size'
        ? `block-size:var(${entry.name})`
        : previewKind === 'radius'
          ? `border-radius:var(${entry.name})`
          : previewKind === 'shadow'
            ? `box-shadow:var(${entry.name})`
            : previewKind === 'motion'
              ? entry.name.startsWith('--duration-')
                ? `transition-duration:var(${entry.name})`
                : `transition-timing-function:var(${entry.name})`
              : '';
  const sample = `<span class="core-style-sample" data-preview="${previewKind}"${sampleStyle ? ` style="${sampleStyle}"` : ''}>
            <span class="core-style-sample__part"${partStyle ? ` style="${partStyle}"` : ''}></span>
            ${previewKind === 'control-gap' ? '<span class="core-style-sample__part"></span>' : ''}
          </span>`;
  return `<span class="core-style-sample-frame" aria-hidden="true">${sample}</span>`;
}

function renderCoreStyleAction(entry) {
  if (!entry.editable) {
    return '<span class="core-style-readonly label-xs">Read only</span>';
  }
  return `<button class="diet-btn-txt core-style-edit" data-size="md" data-variant="secondary" type="button" data-token-edit="foundation" data-token="${escapeHtml(entry.name)}" data-value="${escapeHtml(entry.value)}" aria-label="Edit ${escapeHtml(entry.name)}">
          <span class="diet-btn-txt__label">Edit</span>
        </button>`;
}

function renderCoreStyleRows(tokens) {
  return ['Spacing', 'Control sizes', 'Radii', 'Shadows', 'Motion']
    .map((group) => {
      const entries = tokens.filter((token) => token.group === group);
      if (!entries.length) return '';
      return `
  <section class="core-styles-section" aria-labelledby="core-styles-${group.toLowerCase().replaceAll(' ', '-')}">
    <h3 id="core-styles-${group.toLowerCase().replaceAll(' ', '-')}">${group}</h3>
${entries
  .map(
    (entry) => `
    <div class="core-styles-row" data-token="${escapeHtml(entry.name)}">
      <div class="core-styles-row__identity">
        <span class="token-label">${escapeHtml(entry.name)}</span>
        <span class="token-value" data-token-value="${escapeHtml(entry.name)}">${escapeHtml(entry.value)}</span>
      </div>
      <div class="core-styles-row__preview">
        ${renderCoreStyleSample(entry)}
        ${renderCoreStyleAction(entry)}
      </div>
    </div>`,
  )
  .join('\n')}
  </section>`;
    })
    .filter(Boolean)
    .join('\n');
}

function isWritableColorToken(token) {
  return token.name.startsWith('--color-') && /^#[0-9a-fA-F]{3}(?:[0-9a-fA-F]{3})?$/.test(token.value);
}

function renderColorChip(entry) {
  if (isWritableColorToken(entry)) {
    return `<button class="token-edit-trigger" type="button" data-token-edit="color" data-token="${entry.name}" data-value="${entry.value}" aria-label="Edit ${entry.name}">
          <span class="chip" style="background:var(${entry.name});"></span>
        </button>`;
  }
  return `<span class="token-readonly" aria-label="Read-only ${entry.name}">
          <span class="chip" style="background:var(${entry.name});"></span>
        </span>`;
}

function renderColorRows(tokens) {
  const groups = ['System', 'Neutral', 'Text', 'Roles', 'Focus', 'State', 'Other'];
  return groups
    .map((group) => {
      const entries = tokens.filter((token) => token.group === group);
      if (!entries.length) return '';
      return `
  <h3>${group}</h3>
${entries
    .map(
      (entry) => `
  <div class="row" data-cols="1" data-token="${entry.name}">
    <div class="row-header">${displayName(entry.name)}</div>
    <div class="specdpreview">
      <div class="preview-specs">
        <span class="token-label">${entry.name}</span>
        <span class="token-value" data-token-value="${entry.name}">${entry.value}</span>
      </div>
      <div class="componentpreview">
        ${renderColorChip(entry)}
      </div>
    </div>
  </div>`,
    )
    .join('\n')}`;
    })
    .filter(Boolean)
    .join('\n');
}

async function loadVerifiedIconNames() {
  const manifest = JSON.parse(await fs.readFile(iconsManifestPath, 'utf8'));
  const manifestNames = Object.keys(manifest.symbols ?? {}).sort((a, b) => a.localeCompare(b));
  const sourceFiles = (await fs.readdir(iconsSvgRoot)).filter((name) => name.endsWith('.svg')).sort((a, b) => a.localeCompare(b));
  const sourceNames = sourceFiles.map((name) => path.basename(name, '.svg')).sort((a, b) => a.localeCompare(b));
  const missingSource = manifestNames.filter((name) => !sourceNames.includes(name));
  const missingManifest = sourceNames.filter((name) => !manifestNames.includes(name));
  if (missingSource.length || missingManifest.length) {
    const detail = [
      missingSource.length ? `missing source SVGs: ${missingSource.join(', ')}` : '',
      missingManifest.length ? `source SVGs missing manifest symbols: ${missingManifest.join(', ')}` : '',
    ].filter(Boolean).join('; ');
    throw new Error(`Dieter icon manifest/source mismatch: ${detail}`);
  }
  return manifestNames;
}

