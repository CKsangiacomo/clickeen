function buildLayoutIframeDocument({ html, layoutCss, tokenCss, attributes }) {
  const rootAttributes = Object.entries(attributes ?? {})
    .map(([name, value]) => ` ${name}="${escapeHtml(value)}"`)
    .join('');
  const exampleHtml = html.replace(
    /<div(\s+class=["'][^"']*\bmain-container\b[^"']*["'])/,
    `<div$1${rootAttributes}`,
  );
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>html, body { margin: 0; }\n${tokenCss}\n${layoutCss}</style></head><body>${exampleHtml}</body></html>`;
}

async function generateLayoutsPage() {
  const [layoutHtml, layoutCss, layoutSpecRaw, foundationCss, colorCss, typographyCss, buttonCss] = await Promise.all([
    fs.readFile(layoutHtmlPath, 'utf8'),
    fs.readFile(layoutCssPath, 'utf8'),
    fs.readFile(layoutSpecPath, 'utf8'),
    fs.readFile(foundationCssPath, 'utf8'),
    fs.readFile(colorTokenPath, 'utf8'),
    fs.readFile(typographyCssPath, 'utf8'),
    fs.readFile(buttonCssPath, 'utf8'),
  ]);
  const spec = JSON.parse(layoutSpecRaw);
  const editableTokens = Array.isArray(spec.editableTokens) ? spec.editableTokens : [];
  if (spec.layout !== 'main-container' || editableTokens.length !== 4) {
    throw new Error('Dieter main-container spec is missing its exact editable-token contract.');
  }
  const foundationTokens = new Map(
    parseEditableDieterTokens(foundationCss, TOKEN_FILES.foundation)
      .map((entry) => [entry.token, entry]),
  );
  const tokenRows = editableTokens.map((token) => {
    const entry = foundationTokens.get(token);
    if (!entry?.editable) throw new Error(`Layout token ${token} is not editable through the foundation token path.`);
    return `
          <tr data-token="${escapeHtml(token)}">
            <th class="body-s" scope="row"><code class="body-s">${escapeHtml(token)}</code></th>
            <td class="body-s"><code class="body-s" data-token-value="${escapeHtml(token)}">${escapeHtml(entry.value)}</code></td>
            <td class="body-s diet-table__cell--action"><button class="diet-btn-txt" data-size="md" data-variant="secondary" type="button" data-token-edit="foundation" data-token="${escapeHtml(token)}" data-value="${escapeHtml(entry.value)}" aria-label="Edit ${escapeHtml(token)}"><span class="diet-btn-txt__label">Edit</span></button></td>
          </tr>`;
  }).join('\n');
  const composedSource = `${foundationCss}\n${colorCss}\n${typographyCss}\n${buttonCss}`;
  const examples = Array.isArray(spec.examples)
    ? spec.examples.map((example) => {
        const viewport = LAYOUT_EXAMPLE_VIEWPORTS[example.id];
        if (typeof example.label !== 'string' || !viewport) {
          throw new Error(`Invalid Dieter layout example fixture: ${String(example.id)}`);
        }
        return { ...example, ...viewport };
      })
    : [];
  if (
    examples.map((example) => example.id).join(',') !==
    'full,compact-closed,compact-open'
  ) {
    throw new Error('Dieter main-container spec must define Full, Compact closed, and Compact open examples.');
  }
  const examplesHtml = examples.map((example) => `
    <figure class="layout-example" data-layout-example="${example.id}">
      <figcaption class="label-s">${example.label} — ${example.width} × ${example.height}</figcaption>
      <div class="layout-example__viewport">
        <iframe title="${example.label} main-container example" width="${example.width}" height="${example.height}" srcdoc="${escapeHtml(buildLayoutIframeDocument({ html: layoutHtml, layoutCss, tokenCss: composedSource, attributes: example.attributes }))}"></iframe>
      </div>
    </figure>`).join('\n');
  const html = `${GENERATED_HEADER}
<div class="dieter-preview layouts-page" data-layout-source="dieter/layouts/main-container">
  <style>
    .layout-example { display: grid; gap: var(--space-2); margin: 0; }
    .layout-example__viewport { max-inline-size: 100%; overflow: auto; border: 1px solid var(--role-border); border-radius: var(--control-radius-md); background: var(--role-surface-muted); }
    .layout-example iframe { display: block; border: 0; background: var(--role-surface); }
  </style>
  <p class="body-s">The shared application layout used directly by DevStudio and Roma.</p>
  <details class="foundation-section">
    <summary class="heading-4">Source structure</summary>
    <pre class="body-s"><code class="body-s">${escapeHtml(layoutHtml.trim())}</code></pre>
  </details>
  <section class="foundation-section layout-examples" aria-labelledby="layout-examples">
    <h2 class="heading-4" id="layout-examples">Examples</h2>
${examplesHtml}
  </section>
  <section class="foundation-section" aria-labelledby="layout-properties">
    <h2 class="heading-4" id="layout-properties">Editable properties</h2>
    <div class="diet-table">
      <table class="diet-table__table">
        <thead><tr><th class="label-s" scope="col">Token</th><th class="label-s" scope="col">Source value</th><th class="label-s diet-table__cell--action" scope="col">Action</th></tr></thead>
        <tbody>${tokenRows}</tbody>
      </table>
    </div>
  </section>
</div>
`;
  await writeFileIfChanged(path.join(foundationsRoot, 'layouts.html'), html);
  return editableTokens.length;
}

export async function generateFoundationPages() {
  await fs.mkdir(foundationsRoot, { recursive: true });
  const coreStyleCount = await generateCoreStylesPage();
  const colorCount = await generateColorsPage();
  const iconCount = await generateIconsPage();
  await generateTypographyPage();
  const layoutTokenCount = await generateLayoutsPage();
  return { colorCount, coreStyleCount, iconCount, layoutTokenCount };
}

if (process.argv[1] === scriptPath) {
  generateFoundationPages()
    .then(({ colorCount, coreStyleCount, iconCount, layoutTokenCount }) => {
      console.log(`[generate-foundation-pages] Wrote core styles (${coreStyleCount}), colors (${colorCount}), icons (${iconCount}), and layouts (${layoutTokenCount}) pages.`);
    })
    .catch((error) => {
      console.error('[generate-foundation-pages] Failed.', error instanceof Error ? error.message : String(error));
      process.exit(1);
    });
}
